/** Resolve a slug, numeric code, GATE code or display name to one icon. */
export function branchIconName(branch: string): BranchIconName | undefined {
	const value = branch.trim().toLowerCase();
	if (!value) return undefined;

	const direct = BY_ID[value];
	if (direct) return direct;

	// A sectioned label (`cse-a`, `CSE-B`) names the same branch as its base.
	const sectioned = BY_ID[value.replace(/[-_\s]+[a-d]$/, "")];
	if (sectioned) return sectioned;

	for (const [pattern, icon] of BY_NAME) {
		if (pattern.test(value)) return icon;
	}

	return undefined;
}

/**
 * Full `<svg>` string for markup built at runtime (the merit list re-renders
 * its branch sections from JSON).
 */
export function branchIconSvg(
	branch: string,
	size = 16,
	className = "branch-icon",
): string {
	const icon = branchIconName(branch);
	if (!icon) return "";

	return `<svg class="${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${BRANCH_ICON_BODIES[icon]}</svg>`;
}
