/**
 * The live data feed — one tiny manifest, content-addressed payloads.
 *
 * The app ships a complete syllabus and PYQ snapshot, so it is never empty.
 * This feed is only the *difference*: a manifest lists a 16-hex hash for every
 * table chunk, branch record, GATE record and PYQ bundle. The app compares those
 * hashes with `./bundled.ts` and downloads only the entries whose hash it does
 * not already carry — a code fix in one branch costs a few kilobytes, and the
 * 668 KB of prose is fetched only when the prose itself changed.
 *
 * Nothing here touches `nsh` or the network, so the rules are testable on their
 * own and the publisher (`scripts/data/publish-feed.ts`) writes exactly the
 * shape the app validates.
 */

/** An immutable payload: its content hash and its UTF-8 size. */
export interface FeedFile {
  h: string;
  bytes: number;
}

/** One version of the live feed. `v` is the contract; a newer major is ignored. */
export interface FeedManifest {
  v: 1;
  /** Data snapshot the site published, e.g. `2026-10-27`. */
  generated: string;
  syllabus: {
    snapshot: string;
    /** Entries in each packed table chunk, in the same order as `chunks`. */
    counts: number[];
    /** Hash of each packed table chunk. */
    chunks: string[];
    /** Branch code → hash of its wire record. */
    branches: Record<string, string>;
    /** GATE paper code → hash of its wire record. */
    gate: Record<string, string>;
  };
  pyqs: {
    /** The BEU subject/paper catalog. */
    catalog: FeedFile;
    /** The BEU PDF index. */
    pdfs: FeedFile;
    /** The GATE paper list. */
    gate: FeedFile;
  };
}

/** What the app carries in its binary. Generated by the publisher. */
export interface BundledData {
  snapshot: string;
  counts: number[];
  chunks: string[];
  branches: Record<string, string>;
  gate: Record<string, string>;
  pyqs: {
    catalog: string;
    pdfs: string;
    gate: string;
  };
}

const HASH = /^[0-9a-f]{8,64}$/;
const MAX_COUNTS = 512;

function hashOf(value: unknown): string | null {
  return typeof value === "string" && HASH.test(value) ? value : null;
}

function records(value: unknown): Record<string, string> | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const out: Record<string, string> = {};
  for (const [key, hash] of Object.entries(value as Record<string, unknown>)) {
    const clean = hashOf(hash);
    if (!key || !clean) return null;
    out[key] = clean;
  }
  return out;
}

function fileOf(value: unknown): FeedFile | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const row = value as Record<string, unknown>;
  const h = hashOf(row.h);
  if (!h || typeof row.bytes !== "number" || !Number.isFinite(row.bytes) || row.bytes < 0) return null;
  return { h, bytes: row.bytes };
}

/**
 * Accepts exactly the publisher's shape. A rejected manifest is never partially
 * applied: the caller keeps the bundled snapshot.
 */
export function parseManifest(value: unknown): FeedManifest | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  const root = value as Record<string, unknown>;
  if (root.v !== 1 || typeof root.generated !== "string" || root.generated === "") return null;

  const syllabus = root.syllabus as Record<string, unknown> | undefined;
  const pyqs = root.pyqs as Record<string, unknown> | undefined;
  if (!syllabus || typeof syllabus !== "object" || !pyqs || typeof pyqs !== "object") return null;
  if (typeof syllabus.snapshot !== "string" || syllabus.snapshot === "") return null;

  const counts = syllabus.counts;
  const chunks = syllabus.chunks;
  if (!Array.isArray(counts) || !Array.isArray(chunks)) return null;
  if (counts.length === 0 || counts.length !== chunks.length || counts.length > MAX_COUNTS) return null;
  const cleanCounts: number[] = [];
  for (const count of counts) {
    if (typeof count !== "number" || !Number.isInteger(count) || count < 0) return null;
    cleanCounts.push(count);
  }
  const cleanChunks: string[] = [];
  for (const chunk of chunks) {
    const hash = hashOf(chunk);
    if (!hash) return null;
    cleanChunks.push(hash);
  }

  const branches = records(syllabus.branches);
  const gate = records(syllabus.gate);
  if (!branches || !gate) return null;

  const catalog = fileOf(pyqs.catalog);
  const pdfs = fileOf(pyqs.pdfs);
  const gatePapers = fileOf(pyqs.gate);
  if (!catalog || !pdfs || !gatePapers) return null;

  return {
    v: 1,
    generated: root.generated,
    syllabus: {
      snapshot: syllabus.snapshot,
      counts: cleanCounts,
      chunks: cleanChunks,
      branches,
      gate,
    },
    pyqs: { catalog, pdfs, gate: gatePapers },
  };
}

function sameList(left: string[], right: string[]): boolean {
  if (left.length !== right.length) return false;
  for (let i = 0; i < left.length; i++) if (left[i] !== right[i]) return false;
  return true;
}

function sameRecords(left: Record<string, string>, right: Record<string, string>): boolean {
  const keys = Object.keys(left);
  if (keys.length !== Object.keys(right).length) return false;
  for (const key of keys) if (left[key] !== right[key]) return false;
  return true;
}

/** True when the published feed is byte-for-byte what this build already carries. */
export function sameAsBundled(manifest: FeedManifest, bundled: BundledData): boolean {
  if (!sameList(manifest.syllabus.counts.map(String), bundled.counts.map(String))) return false;
  if (!sameList(manifest.syllabus.chunks, bundled.chunks)) return false;
  if (!sameRecords(manifest.syllabus.branches, bundled.branches)) return false;
  if (!sameRecords(manifest.syllabus.gate, bundled.gate)) return false;
  return (
    manifest.pyqs.catalog.h === bundled.pyqs.catalog &&
    manifest.pyqs.pdfs.h === bundled.pyqs.pdfs &&
    manifest.pyqs.gate.h === bundled.pyqs.gate
  );
}

/**
 * Payload hashes the device does not already have in its binary. This is the
 * whole download: unchanged branches, chunks and indexes cost zero bytes.
 */
export function requiredHashes(manifest: FeedManifest, bundled: BundledData): string[] {
  const missing = new Set<string>();
  const chunks = new Set(bundled.chunks);
  for (const hash of manifest.syllabus.chunks) if (!chunks.has(hash)) missing.add(hash);
  for (const [code, hash] of Object.entries(manifest.syllabus.branches)) {
    if (bundled.branches[code] !== hash) missing.add(hash);
  }
  for (const [code, hash] of Object.entries(manifest.syllabus.gate)) {
    if (bundled.gate[code] !== hash) missing.add(hash);
  }
  if (manifest.pyqs.catalog.h !== bundled.pyqs.catalog) missing.add(manifest.pyqs.catalog.h);
  if (manifest.pyqs.pdfs.h !== bundled.pyqs.pdfs) missing.add(manifest.pyqs.pdfs.h);
  if (manifest.pyqs.gate.h !== bundled.pyqs.gate) missing.add(manifest.pyqs.gate.h);
  return [...missing];
}

/** Stable identity of a manifest; used to skip re-applying the copy already active. */
export function manifestSignature(manifest: FeedManifest): string {
  return JSON.stringify([
    manifest.syllabus.snapshot,
    manifest.syllabus.counts,
    manifest.syllabus.chunks,
    manifest.syllabus.branches,
    manifest.syllabus.gate,
    manifest.pyqs.catalog.h,
    manifest.pyqs.pdfs.h,
    manifest.pyqs.gate.h,
  ]);
}
