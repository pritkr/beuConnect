#!/usr/bin/env bash
# Turns `android/google-services.json` into the resource values Firebase reads.
#
# The host is built with aapt2, not Gradle, so nothing applies the
# `com.google.gms.google-services` plugin that would normally copy these five
# strings out of the JSON into `res/values`. `FirebaseInitProvider` reads them
# by resource name at process start; without them `FirebaseApp.getApps()` is
# empty and push is simply unavailable — which is the correct state for a
# checkout that has no Firebase project, so a missing file is not an error.
#
# Usage:
#   ./scripts/firebase-config.sh           # generate, or clear if the JSON is gone
#   ./scripts/firebase-config.sh --check   # 0 if up to date, 1 if it needs a run
#
# `android/google-services.json` is downloaded from the Firebase console
# (Project settings → Your apps → Android app → google-services.json) and is
# never committed: see the ignore list in the repository root.
set -euo pipefail
cd "$(dirname "$0")/.."

JSON="android/google-services.json"
OUT="android/res/values/firebase.xml"

# Python, not bun: this runs in the Android build, whose other steps
# (build-android-host.sh) already assume python3 and nothing else installed.
generate() {
  python3 - "$JSON" <<'PY'
import json
import sys
from xml.sax.saxutils import escape

with open(sys.argv[1]) as handle:
    doc = json.load(handle)

info = doc.get("project_info") or {}
clients = doc.get("client") or []
if not clients:
    raise SystemExit("google-services.json has no client entry")
client = clients[0]
api_keys = client.get("api_key") or []

values = {
    "google_app_id": (client.get("client_info") or {}).get("mobilesdk_app_id") or "",
    "gcm_defaultSenderId": info.get("project_number") or "",
    "google_api_key": api_keys[0].get("current_key") if api_keys else "",
    "project_id": info.get("project_id") or "",
    "google_storage_bucket": info.get("storage_bucket") or "",
}
database = info.get("firebase_url")
if database:
    values["firebase_database_url"] = database

for name in ("google_app_id", "gcm_defaultSenderId", "project_id"):
    if not values[name]:
        raise SystemExit(f"google-services.json is missing {name}")

print('<?xml version="1.0" encoding="utf-8"?>')
print("<!--")
print("    Generated by scripts/firebase-config.sh from android/google-services.json.")
print("    Do not edit: rerun the script after downloading a new json.")
print("-->")
print("<resources>")
for name, value in values.items():
    print(f'    <string name="{name}">{escape(value)}</string>')
print("</resources>")
PY
}

if [ ! -f "$JSON" ]; then
  if [ "${1:-}" = "--check" ]; then
    [ -f "$OUT" ] && { echo "$OUT exists but $JSON is gone" >&2; exit 1; }
    echo "· no $JSON — building without push notifications"
    exit 0
  fi
  # A stale file from a previous project would point the build at a Firebase
  # app that no longer exists, so its absence is written as absence.
  rm -f "$OUT"
  echo "· no $JSON — push notifications are disabled in this build"
  exit 0
fi

CONTENT="$(generate)"

if [ "${1:-}" = "--check" ]; then
  if [ ! -f "$OUT" ] || [ "$(cat "$OUT")" != "$CONTENT" ]; then
    echo "$OUT is stale — run ./scripts/firebase-config.sh" >&2
    exit 1
  fi
  echo "✓ $OUT matches $JSON"
  exit 0
fi

printf '%s\n' "$CONTENT" > "$OUT"
echo "✓ $OUT"
