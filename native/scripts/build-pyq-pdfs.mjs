#!/usr/bin/env bun
/**
 * Publishes the BEU previous-year papers and indexes them for the app.
 *
 * Input, both already in the repository:
 *
 *   beu_dataset/pdfs/*.pdf                    299 downloaded papers
 *   beu_dataset/beu_btech_question_papers.csv 1,394 rows describing them
 *
 * Output, both generated — never hand-edited:
 *
 *   public/PYQPDFs/<file>.pdf         the papers, served by the site
 *   public/data/pyq-pdfs.json         the site-side index
 *   src/features/pyqs/pdf-catalog.ts  the app's packed copy of the same index
 *
 * The rules — which branch a paper belongs to, which duplicated download wins,
 * how a year is read — live in `src/features/pyqs/pdf-build.ts`, because that
 * module is pure and therefore tested (`qa/unit/pyq-pdfs.test.ts`). This file
 * is only the disk around it.
 *
 *   bun scripts/build-pyq-pdfs.mjs            # copy, build, write
 *   bun scripts/build-pyq-pdfs.mjs --check    # report; write nothing
 *
 * It is rerunnable: files are mirrored (a paper removed from the dataset is
 * removed from `public/`), and a run with no input change writes nothing —
 * the snapshot date is kept when the papers are identical, so a rebuild does
 * not produce a one-line diff.
 */

import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { PDF_BASE, buildPapers, packPapers, parseCsv } from "../src/features/pyqs/pdf-build.ts";

const NATIVE = resolve(import.meta.dir, "..");
const REPO = resolve(NATIVE, "..");

const SOURCE_DIR = join(REPO, "beu_dataset/pdfs");
const CSV_FILE = join(REPO, "beu_dataset/beu_btech_question_papers.csv");
const PUBLIC_DIR = join(REPO, "public/PYQPDFs");
const JSON_FILE = join(REPO, "public/data/pyq-pdfs.json");
const TS_FILE = join(NATIVE, "src/features/pyqs/pdf-catalog.ts");

const CHECK_ONLY = process.argv.includes("--check");
const TODAY = new Date().toISOString().slice(0, 10);

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} KB`;
const mb = (bytes) => `${(bytes / 1024 / 1024).toFixed(1)} MB`;

function plural(count, one, many = `${one}s`) {
  return `${count} ${count === 1 ? one : many}`;
}

/* --------------------------------------------------------------- the files */

/**
 * Mirrors `beu_dataset/pdfs` into `public/PYQPDFs`: every paper copied, nothing
 * else kept. The public folder becomes the source of truth for "which PDFs
 * exist", so a file the dataset lost stops being indexed in the same run.
 */
function syncFiles() {
  if (!existsSync(SOURCE_DIR)) throw new Error(`no source folder: ${SOURCE_DIR}`);
  const source = readdirSync(SOURCE_DIR)
    .filter((name) => name.toLowerCase().endsWith(".pdf"))
    .sort();
  if (source.length === 0) throw new Error(`no PDFs in ${SOURCE_DIR}`);

  const present = existsSync(PUBLIC_DIR) ? new Set(readdirSync(PUBLIC_DIR)) : new Set();
  const wanted = new Set(source);
  let copied = 0;
  let removed = 0;

  if (!CHECK_ONLY) mkdirSync(PUBLIC_DIR, { recursive: true });
  for (const name of source) {
    if (present.has(name)) {
      const to = join(PUBLIC_DIR, name);
      if (statSync(to).size === statSync(join(SOURCE_DIR, name)).size) continue;
      if (!CHECK_ONLY) copyFileSync(join(SOURCE_DIR, name), to);
      copied += 1;
      continue;
    }
    if (!CHECK_ONLY) copyFileSync(join(SOURCE_DIR, name), join(PUBLIC_DIR, name));
    copied += 1;
  }
  for (const name of present) {
    if (wanted.has(name)) continue;
    if (!CHECK_ONLY) rmSync(join(PUBLIC_DIR, name), { force: true });
    removed += 1;
  }

  return { copied, removed, names: source };
}

/* ------------------------------------------------ the generated app module */

function moduleText(papers, snapshot) {
  const wire = packPapers(papers, snapshot);
  const codes = new Set(papers.map((paper) => paper.subjectCode)).size;
  return `/* eslint-disable */
/**
 * Every BEU previous-year paper PDF the app can open.
 *
 * GENERATED by ./scripts/build-pyq-pdfs.mjs — do not hand-edit.
 *
 * ${plural(papers.length, "paper")} · ${plural(codes, "subject code")} · ${snapshot}.
 */

export const SNAPSHOT = ${JSON.stringify(snapshot)};

/** One PDF. Only the file name is stored; \`url\` is derived from it. */
export interface PdfPaper {
  file: string;
  url: string;
  year: number;
  subjectCode: string;
  subjectSlug: string;
  subjectName: string;
  branchKey: string;
  branchName: string;
  /** 1–8, or 0 when the source row named no semester. */
  semester: number;
  /** "v2" for a re-examination of the same year, "" for the ordinary paper. */
  variant: string;
}

interface Packed {
  g: string;
  u: string;
  /** [branchKey, branchName] */
  b: [string, string][];
  s: string[];
  n: string[];
  v: string[];
  /** [file, year, subjectCode, slugIndex, nameIndex, branchIndex, semester, variantIndex] */
  p: [string, number, string, number, number, number, number, number][];
}

/** Expands the packed wire form into the papers it stands for. */
export function decode(raw: string): PdfPaper[] {
  const wire = JSON.parse(raw) as Packed;
  return wire.p.map(([file, year, subjectCode, slug, name, branch, semester, variant]) => ({
    file,
    url: \`\${wire.u}\${encodeURIComponent(file)}\`,
    year,
    subjectCode,
    subjectSlug: wire.s[slug],
    subjectName: wire.n[name],
    branchKey: wire.b[branch][0],
    branchName: wire.b[branch][1],
    semester,
    variant: wire.v[variant],
  }));
}

/**
 * The packed wire form. Call \`decode\`; this is not the papers' shape.
 */
export const RAW = ${JSON.stringify(JSON.stringify(wire))};
`;
}

/* ---------------------------------------------------------------- the index */

function indexText(papers, generated) {
  return `${JSON.stringify({ generated, base: PDF_BASE, papers }, null, 2)}\n`;
}

/** `SNAPSHOT` and the decoded papers of the module currently on disk. */
async function readExisting() {
  if (!existsSync(TS_FILE)) return null;
  try {
    const module = await import(`${pathToFileURL(TS_FILE).href}?v=${Date.now()}`);
    if (typeof module.decode !== "function" || typeof module.RAW !== "string") return null;
    return {
      snapshot: typeof module.SNAPSHOT === "string" ? module.SNAPSHOT : "",
      papers: module.decode(module.RAW),
    };
  } catch {
    // A corrupt or half-written module is what this script exists to replace.
    return null;
  }
}

/**
 * Imports the module we are about to write and proves it decodes back to the
 * papers the builder produced, field order included. Writing a smaller index
 * that lost a paper is worse than writing none.
 */
async function verify(module, papers) {
  const scratch = join(tmpdir(), `beu-pyq-pdfs-verify-${process.pid}.ts`);
  writeFileSync(scratch, module);
  const built = await import(`${pathToFileURL(scratch).href}?v=${Date.now()}`);
  const decoded = built.decode(built.RAW);
  rmSync(scratch, { force: true });
  if (JSON.stringify(decoded) !== JSON.stringify(papers)) {
    throw new Error("packed round-trip mismatch — refusing to write");
  }
}

/* --------------------------------------------------------------------- run */

const files = syncFiles();
const records = parseCsv(readFileSync(CSV_FILE, "utf8"));
const papers = buildPapers(records, new Set(files.names));
if (papers.length === 0) throw new Error("the index came out empty — refusing to write");

const existing = await readExisting();
const unchanged = existing !== null && JSON.stringify(existing.papers) === JSON.stringify(papers);
// Keeping the old date when nothing changed makes a rebuild a no-op instead of
// a one-line diff, and `--check` in CI becomes a real freshness test.
const snapshot = unchanged ? existing.snapshot : TODAY;

const module = moduleText(papers, snapshot);
const json = indexText(papers, snapshot);
await verify(module, papers);

const withFile = records.filter((record) => record.filename && files.names.includes(record.filename)).length;
const bytes = files.names.reduce((total, name) => total + statSync(join(SOURCE_DIR, name)).size, 0);
const branches = new Set(papers.map((paper) => paper.branchKey));
const codes = new Set(papers.map((paper) => paper.subjectCode));
const dropped = withFile - papers.length;

console.log(
  `${plural(files.names.length, "PDF")} · ${plural(papers.length, "index entry", "index entries")} · ${mb(bytes)} in public/PYQPDFs`,
);
console.log(
  `  ${plural(codes.size, "subject code")} · ${plural(branches.size, "branch", "branches")} · ${plural(dropped, "duplicate")} dropped · ${plural(records.length - withFile, "row")} without a file`,
);
if (files.copied > 0) console.log(`  ${CHECK_ONLY ? "would copy" : "copied"} ${plural(files.copied, "file")}`);
if (files.removed > 0) console.log(`  ${CHECK_ONLY ? "would remove" : "removed"} ${plural(files.removed, "file")}`);
console.log(`  index ${kb(Buffer.byteLength(json))} JSON · ${kb(Buffer.byteLength(module))} packed module`);

if (CHECK_ONLY) {
  const stale =
    files.copied > 0 ||
    files.removed > 0 ||
    !existsSync(JSON_FILE) ||
    readFileSync(JSON_FILE, "utf8") !== json ||
    !existsSync(TS_FILE) ||
    readFileSync(TS_FILE, "utf8") !== module;
  console.log(stale ? "  stale: run without --check to rebuild" : "  current");
  process.exit(stale ? 1 : 0);
}

const written =
  (existsSync(JSON_FILE) && readFileSync(JSON_FILE, "utf8") === json ? 0 : 1) +
  (existsSync(TS_FILE) && readFileSync(TS_FILE, "utf8") === module ? 0 : 1);
if (written === 0) {
  console.log("  unchanged");
} else {
  writeFileSync(JSON_FILE, json);
  writeFileSync(TS_FILE, module);
  console.log(`  wrote public/data/pyq-pdfs.json and src/features/pyqs/pdf-catalog.ts`);
}
