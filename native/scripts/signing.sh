#!/usr/bin/env bash
# The release signing identity — once per machine, never in git.
#
#   ./scripts/signing.sh            # create it if it does not exist
#   ./scripts/signing.sh --show     # print where it is and which key the APK uses
#
# A shared APK has to upgrade itself: Android refuses an install signed by a
# different key than the one already on the phone. The debug keystore is
# machine-local, so a build from a second machine would be a different signer
# and every student would have to uninstall first. A release key at a fixed path
# removes that class of failure.
#
# Files live outside the repository, in `~/.config/beuconnect/`:
#   signing.env             KEYSTORE / KEY_ALIAS / KEY_PASS, read by the build
#   beuconnect-release.jks  the key itself (PKCS12, password-protected)
#
# `package-android.sh`, `build-android-host.sh` and `release.sh` all source the
# env file, so creating it once is enough. Never commit either file; losing the
# key means students must uninstall to take a future build.
set -euo pipefail

DIR="$HOME/.config/beuconnect"
ENV_FILE="$DIR/signing.env"
KEYSTORE="$DIR/beuconnect-release.jks"
ALIAS="beuconnect"

if [ "${1:-}" = "--show" ]; then
  if [ -f "$ENV_FILE" ]; then
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    echo "keystore  $KEYSTORE"
    echo "alias     $KEY_ALIAS"
    echo "apk       .nsh/out/BEUConnect.apk"
    if command -v apksigner >/dev/null && [ -f ".nsh/out/BEUConnect.apk" ]; then
      apksigner verify --print-certs .nsh/out/BEUConnect.apk 2>/dev/null | head -4
    fi
  else
    echo "no signing identity yet — run ./scripts/signing.sh"
  fi
  exit 0
fi

if [ -f "$ENV_FILE" ] && [ -f "$KEYSTORE" ]; then
  echo "✓ signing identity already exists: $KEYSTORE"
  exit 0
fi

command -v keytool >/dev/null || { echo "missing keytool (source ~/.config/nsh/env.sh)" >&2; exit 1; }
mkdir -p "$DIR"
chmod 700 "$DIR"

# 28 hex characters: apksigner and the shell both take it as a literal, and a
# stray quote would silently truncate it.
PASS="$(openssl rand -hex 14)"

keytool -genkeypair \
  -keystore "$KEYSTORE" \
  -storetype PKCS12 \
  -alias "$ALIAS" \
  -keyalg RSA -keysize 4096 -validity 10950 \
  -storepass "$PASS" -keypass "$PASS" \
  -dname "CN=BEUConnect, O=BEUConnect, L=Patna, ST=Bihar, C=IN" \
  >/dev/null 2>&1

cat >"$ENV_FILE" <<EOF
# BEUConnect release signing identity. Generated by scripts/signing.sh.
# Do not commit, do not paste into a chat: with this file anyone can sign an
# "update" Android will install over the real app.
export KEYSTORE="$KEYSTORE"
export KEY_ALIAS="$ALIAS"
export KEY_PASS="$PASS"
EOF
chmod 600 "$ENV_FILE" "$KEYSTORE"

echo "✓ created $KEYSTORE"
echo "  credentials in $ENV_FILE (chmod 600, outside the repository)"
echo "  back both up: without them no future build can update an installed app"
