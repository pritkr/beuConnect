/**
 * Publishes the app's bundled data as the live feed the app checks at launch.
 *
 * ── how to update every installed app ──────────────────────────────────────
 *
 *   bun scripts/data/publish-feed.ts --site   # write the site's public/data/app
 *   bun scripts/data/publish-feed.ts          # write dist/feed, for inspection
 *   bun scripts/data/publish-feed.ts --check  # exit 1 if bundled.ts has drifted
 *
 * Then deploy the site. The next check (at most an hour after a launch, or the
 * button on Settings → Offline data) downloads only the payloads whose hash
 * changed, because every file is content-addressed:
 *
 *   manifest.json        1 list: a 16-hex hash per chunk, branch, GATE record
 *                        and PYQ bundle, plus each bundle's UTF-8 size
 *   files/<hash>.txt     one immutable payload per distinct hash
 *
 * So a one-word correction to a single syllabus topic produces one new chunk
 * (a few dozen kilobytes), not the 668 KB table; a new paper year produces one
 * new `pyqs.catalog` payload (~98 KB) and nothing else. Everything unchanged
 * keeps the hash the app shipped with and costs zero bytes.
 *
 * ## Why the hashes are written into `bundled.ts`
 *
 * The app has to know what it already carries without downloading anything. The
 * generated `src/features/data-feed/bundled.ts` is that list: at runtime a
 * payload is fetched only when the manifest names a hash that is not in it
 * (see `requiredHashes` in `src/features/data-feed/model.ts`). So run this in
 * the same commit as the data change — `--check` fails the gate otherwise.
 *
 * ## Why one manifest, applied whole
 *
 * Branch records carry indexes into the shared prose table. Half a new table
 * would point every subject at the wrong paragraph, so the app writes the
 * manifest last, after every payload it names is already on the device.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { BRANCH_WIRE, DATA_SNAPSHOT, GATE_WIRE } from "../../src/features/syllabus/data/packs.ts";
import { CHUNKS, COUNTS } from "../../src/features/syllabus/data/table/index.ts";
import { RAW as CATALOG_RAW } from "../../src/features/pyqs/catalog-data.ts";
import { RAW as PDF_RAW } from "../../src/features/pyqs/pdf-catalog.ts";
import { RAW as GATE_RAW } from "../../src/features/pyqs/gate-data.ts";
import type { BundledData, FeedManifest } from "../../src/features/data-feed/model.ts";

const BUNDLED_FILE = new URL("../../src/features/data-feed/bundled.ts", import.meta.url);
const DIST = new URL("../../dist/feed/", import.meta.url);
const SITE = new URL("../../../public/data/app/", import.meta.url);

const args = new Set(process.argv.slice(2));
const check = args.has("--check");
const out = args.has("--site") ? SITE : DIST;

/** 16 hex chars: 64 bits of SHA-256, the same shape `model.ts` validates. */
function hash(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex").slice(0, 16);
}

function bytes(text: string): number {
  return Buffer.byteLength(text, "utf8");
}

// ── the payloads ────────────────────────────────────────────────────────────

if (COUNTS.length !== CHUNKS.length) {
  console.error(`COUNTS has ${COUNTS.length} entries but CHUNKS has ${CHUNKS.length}.`);
  process.exit(1);
}

/** hash → text, in insert order, so the manifest is byte-stable between runs. */
const files = new Map<string, string>();

function payload(text: string): string {
  const h = hash(text);
  if (!files.has(h)) files.set(h, text);
  return h;
}

const chunkHashes = CHUNKS.map(payload);
const branchHashes: Record<string, string> = {};
for (const [code, wire] of Object.entries(BRANCH_WIRE)) branchHashes[code] = payload(wire);
const gateHashes: Record<string, string> = {};
for (const [code, wire] of Object.entries(GATE_WIRE)) gateHashes[code] = payload(wire);

const catalog = { h: payload(CATALOG_RAW), bytes: bytes(CATALOG_RAW) };
const pdfs = { h: payload(PDF_RAW), bytes: bytes(PDF_RAW) };
const gate = { h: payload(GATE_RAW), bytes: bytes(GATE_RAW) };

const bundled: BundledData = {
  snapshot: DATA_SNAPSHOT,
  counts: COUNTS,
  chunks: chunkHashes,
  branches: branchHashes,
  gate: gateHashes,
  pyqs: { catalog: catalog.h, pdfs: pdfs.h, gate: gate.h },
};

const manifest: FeedManifest = {
  v: 1,
  generated: new Date().toISOString().slice(0, 10),
  syllabus: {
    snapshot: DATA_SNAPSHOT,
    counts: COUNTS,
    chunks: chunkHashes,
    branches: branchHashes,
    gate: gateHashes,
  },
  pyqs: { catalog, pdfs, gate },
};

// ── the generated file ──────────────────────────────────────────────────────

const source = `/* eslint-disable */
/**
 * GENERATED by \`scripts/data/publish-feed.ts\` — do not hand-edit.
 *
 * The content hashes of the data in this build. The live feed compares against
 * these, so unchanged syllabus prose, branch records and PYQ bundles are reused
 * from the binary instead of being downloaded into Storage.
 */
import type { BundledData } from "./model";

export const BUNDLED: BundledData = ${JSON.stringify(bundled, null, 2)};
`;

if (check) process.exit(drift());

report();
process.exit(write());

/** What this run covers, in the units a student would recognise. */
function report(): void {
  const total = [...files.values()].reduce((sum, text) => sum + bytes(text), 0);
  const rows = COUNTS.reduce((sum, count) => sum + count, 0);
  console.log(`snapshot   ${DATA_SNAPSHOT}`);
  console.log(`chunks     ${CHUNKS.length} · ${rows} rows`);
  console.log(`branches   ${Object.keys(branchHashes).join(" ")}`);
  console.log(`gate       ${Object.keys(gateHashes).length} papers`);
  console.log(`pyqs       catalog ${size(catalog.bytes)} · pdfs ${size(pdfs.bytes)} · gate ${size(gate.bytes)}`);
  console.log(`payloads   ${files.size} distinct · ${size(total)}`);
}

function size(value: number): string {
  if (value < 1024) return `${value} B`;
  if (value < 1024 * 1024) return `${(value / 1024).toFixed(1)} KB`;
  return `${(value / (1024 * 1024)).toFixed(2)} MB`;
}

// ── --check ─────────────────────────────────────────────────────────────────

/** Reports which part of the shipped hashes no longer matches the data. */
function drift(): number {
  const path = BUNDLED_FILE.pathname;
  if (!existsSync(path)) {
    console.error(`Missing ${path}. Run without --check to generate it.`);
    return 1;
  }
  const current = normalize(readFileSync(path, "utf8"));
  if (current === normalize(source)) {
    console.log("bundled.ts is current.");
    return 0;
  }
  console.error("bundled.ts is stale:");
  const shipped = shippedData(current);
  if (!shipped) {
    console.error("  it does not parse; regenerate it");
    return 1;
  }
  for (const line of differences(shipped)) console.error(`  ${line}`);
  console.error("Run `bun scripts/data/publish-feed.ts` and commit the result.");
  return 1;
}

function normalize(text: string): string {
  return `${text.replace(/\r\n/g, "\n").trimEnd()}\n`;
}

function shippedData(source: string): BundledData | null {
  const at = source.indexOf("{", source.indexOf("BUNDLED"));
  if (at < 0) return null;
  try {
    return JSON.parse(source.slice(at).replace(/;\s*$/, "")) as BundledData;
  } catch {
    return null;
  }
}

/** One line per category that changed, so the fix is obvious without a diff. */
function differences(shipped: BundledData): string[] {
  const lines: string[] = [];
  if (shipped.snapshot !== bundled.snapshot) {
    lines.push(`snapshot   ${shipped.snapshot || "(none)"} → ${bundled.snapshot}`);
  }
  if (shipped.counts.join(",") !== bundled.counts.join(",")) {
    lines.push(`counts     ${shipped.counts.length} entries → ${bundled.counts.length}`);
  }
  const chunks = changed(shipped.chunks, bundled.chunks);
  if (chunks > 0) lines.push(`chunks     ${chunks} of ${bundled.chunks.length} changed`);
  const branches = changedRecord(shipped.branches, bundled.branches);
  if (branches > 0) lines.push(`branches   ${branches} changed`);
  const gates = changedRecord(shipped.gate, bundled.gate);
  if (gates > 0) lines.push(`gate       ${gates} changed`);
  for (const kind of ["catalog", "pdfs", "gate"] as const) {
    if (shipped.pyqs?.[kind] === bundled.pyqs[kind]) continue;
    lines.push(`pyqs.${kind}`.padEnd(10) + " changed");
  }
  if (lines.length === 0) lines.push("formatting only");
  return lines;
}

function changed(left: string[], right: string[]): number {
  let count = left.length === right.length ? 0 : Math.abs(left.length - right.length);
  for (let i = 0; i < Math.min(left.length, right.length); i++) if (left[i] !== right[i]) count += 1;
  return count;
}

function changedRecord(left: Record<string, string>, right: Record<string, string>): number {
  const keys = new Set([...Object.keys(left ?? {}), ...Object.keys(right)]);
  let count = 0;
  for (const key of keys) if (left?.[key] !== right[key]) count += 1;
  return count;
}

// ── write ───────────────────────────────────────────────────────────────────

function write(): number {
  const root = out.pathname;
  const dir = join(root, "files");
  mkdirSync(dir, { recursive: true });

  for (const [h, text] of files) writeFileSync(join(dir, `${h}.txt`), text, "utf8");
  writeFileSync(join(root, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  writeFileSync(BUNDLED_FILE.pathname, source, "utf8");

  // Content-addressed files from an older publish are unreachable: the manifest
  // is the only index, and it was just replaced.
  let pruned = 0;
  for (const name of readdirSync(dir)) {
    if (!name.endsWith(".txt")) continue;
    if (files.has(name.slice(0, -4))) continue;
    rmSync(join(dir, name), { force: true });
    pruned += 1;
  }

  console.log(`wrote      ${root}`);
  console.log(`           bundled.ts · manifest.json · ${files.size} payloads${pruned > 0 ? ` · ${pruned} pruned` : ""}`);
  if (out === SITE) console.log("next       deploy the site, then installed apps pick this up on their next check");
  return 0;
}
