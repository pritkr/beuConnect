#!/usr/bin/env bun
/**
 * Regenerates `qa/push-targets.ts`: every route name the app source pushes.
 *
 * The route sweep needs the list of `nav.push("…")` / `nav.replace("…")`
 * literals to prove each one resolves to a registered route. Tests run inside
 * the app sandbox, which has no filesystem capability (`nsh.json` is owned by
 * the lead), so the list cannot be grepped at test time. It is grepped here
 * instead and checked in:
 *
 *   bun qa/scan-push-targets.mjs          # rewrite qa/push-targets.ts
 *   bun qa/scan-push-targets.mjs --check  # exit 1 when the check-in is stale
 *
 * `qa/run-tests.sh` runs the `--check` before the suite, so a name added to
 * `src/` without regenerating this file fails the gate instead of shipping.
 *
 * Dynamic targets (`push(item.route)`) are covered separately: the array
 * literals in `more.tsx` and `home/index.tsx` are route names too, so they are
 * picked up as `route: "…"` entries.
 *
 * Each file is scanned as one string (not line by line) so a call whose literal
 * sits on the next line is still found; the line number is recovered from the
 * match offset.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const ROOT = new URL("../", import.meta.url).pathname;
const SRC = join(ROOT, "src");
const OUT = join(ROOT, "qa", "push-targets.ts");
const SKIP = new Set(["node_modules", ".nsh", "dist"]);

/**
 * `nav.push("x")` / `nav.replace("x")` / `route: "x"` — the three ways a name is
 * written. Only a `nav`-receiver counts for push/replace: `lines.push("…")` and
 * `name.replace(" Engineering", "")` are not navigation, and `route: "…"` is a
 * navigation target only in the shell's link tables.
 */
const PATTERNS = [
  { kind: "push", re: /\b(?:props\.nav|nav)\.push\(\s*["']([^"']+)["']/g },
  { kind: "replace", re: /\b(?:props\.nav|nav)\.replace\(\s*["']([^"']+)["']/g },
  { kind: "route-literal", re: /\broute:\s*["']([^"']+)["']/g },
];

/** A route name, not prose, an icon or an HTTP path. */
function looksLikeRoute(name) {
  return /^[a-z][a-z0-9]*(?:\.[a-z0-9]+)*$/.test(name);
}

/** `route: "…"` is only a navigation target in the shell's link tables. */
function routeLiteralFile(path) {
  const relativePath = relative(ROOT, path);
  return relativePath.startsWith("src/app/") || relativePath.startsWith("src/features/home/");
}

/** The number of newlines before `index`, plus one. */
function lineAt(text, index) {
  let line = 1;
  for (let at = text.indexOf("\n"); at !== -1 && at < index; at = text.indexOf("\n", at + 1)) line += 1;
  return line;
}

/** The rest of the line the match starts on, for the union-type check. */
function restOfLine(text, index) {
  const end = text.indexOf("\n", index);
  return text.slice(index, end === -1 ? text.length : end);
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      if (SKIP.has(entry.name)) return [];
      const path = join(dir, entry.name);
      if (entry.isDirectory()) return walk(path);
      return /\.(ts|tsx)$/.test(entry.name) && !/\.test\.tsx?$/.test(entry.name) ? [path] : [];
    }),
  );
  return files.flat().sort();
}

const hits = [];

for (const path of await walk(SRC)) {
  const text = await readFile(path, "utf8");
  const fileHits = [];
  for (const { kind, re } of PATTERNS) {
    if (kind === "route-literal" && !routeLiteralFile(path)) continue;
    re.lastIndex = 0;
    let match;
    while ((match = re.exec(text)) !== null) {
      if (!looksLikeRoute(match[1])) continue;
      // `route: "subject" | "topic"` is a union type, not a navigation target.
      if (restOfLine(text, match.index + match[0].length).trimStart().startsWith("|")) continue;
      fileHits.push({ target: match[1], file: relative(ROOT, path), line: lineAt(text, match.index), kind, at: match.index });
    }
  }
  // Source order, so a regenerated file only moves when the source moves.
  fileHits.sort((left, right) => left.at - right.at);
  for (const { target, file, line, kind } of fileHits) hits.push({ target, file, line, kind });
}

const seen = new Set();
const unique = hits.filter((hit) => {
  const key = `${hit.target}\u0000${hit.file}\u0000${hit.line}`;
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

const body = `// Generated by \`bun qa/scan-push-targets.mjs\` — do not edit by hand.
//
// Every route name written as a push/replace target (or a \`route:\` literal the
// app navigates with) anywhere under \`src/\`. \`qa/registry.test.ts\` asserts each
// one resolves in \`ROUTE_MAP\`; \`qa/run-tests.sh\` re-runs the scanner in
// \`--check\` mode first, so a stale list cannot pass.

export interface PushTarget {
  /** What the source hands \`nav.push\`. */
  target: string;
  /** Where it is written, for the failure message. */
  file: string;
  line: number;
  kind: "push" | "replace" | "route-literal";
}

export const PUSH_TARGETS: PushTarget[] = ${JSON.stringify(unique, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (current !== body) {
    console.error("qa/push-targets.ts is stale — run: bun qa/scan-push-targets.mjs");
    process.exit(1);
  }
  console.log(`push targets up to date (${unique.length})`);
} else {
  await writeFile(OUT, body);
  console.log(`wrote ${unique.length} push targets to qa/push-targets.ts`);
}
